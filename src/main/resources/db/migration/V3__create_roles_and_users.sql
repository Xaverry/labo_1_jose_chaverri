CREATE TABLE role (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      nombre VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE usuario (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nombre VARCHAR(50) NOT NULL UNIQUE,
                         password VARCHAR(255) NOT NULL,
                         role_id BIGINT NOT NULL,

                         CONSTRAINT fk_usuario_role
                             FOREIGN KEY (role_id)
                                 REFERENCES role(id)
);

